#!/usr/bin/env python3
"""
Parse raw benchmark outputs and generate LaTeX table comparing
homogeneous vs heterogeneous variants.

This script reads the raw benchmark output files generated by
generate_raw_outputs.py and creates a LaTeX table for the paper.
"""

import re
from pathlib import Path
from typing import Optional, Dict, Tuple
import sys
import argparse
from utils import get_cpu_model

# Dataset groups: (base_name, display_name)
# Edit this list to control which datasets appear in the table
DATASETS = [
    ("uniform-4digit-1M", "Uniform 4-digit (1M)"),
    ("uniform-8digit-1M", "Uniform 8-digit (1M)"),
    ("uniform-16digit-1M", "Uniform 16-digit (1M)"),
    ("uniform-1to20-1M", "Uniform 1-20 digits (1M)"),
    ("natural-8-1M", "Natural-8 (1M)"),
    ("natural-16-1M", "Natural-16 (1M)"),
    ("citm_catalog_integers", "CITM Catalog"),
    ("twitterjson_integers", "Twitter JSON"),
    ("stackoverflow_unix_timestamps_integers", "StackOverflow Timestamps"),
    ("cit_patents_citing_integers", "US Patents"),
]


def parse_benchmark_output(file_path: Path) -> Optional[Dict[str, float]]:
    """
    Parse a benchmark output file and extract timing information.

    Returns a dict with algorithm names as keys and ns/d (ns per item) as values.
    Returns None if parsing fails.
    """
    try:
        with open(file_path, 'r') as f:
            content = f.read()
    except FileNotFoundError:
        print(f"WARNING: File not found: {file_path}")
        return None

    results = {}

    # Parse the AVX-512+champagne_lemire line(s)
    # Format: "avx-512+champagne_lemire              :  X.XX ns/d ..."
    pattern = r'avx-512\+champagne_lemire\s*:\s*(\d+\.\d+)\s*ns/d'
    matches = re.findall(pattern, content)

    if matches:
        # Take the best (minimum) time if multiple runs
        times = [float(m) for m in matches]
        results['champagne_lemire'] = min(times)

    return results if results else None


def extract_auto_selection(file_path: Path) -> Optional[str]:
    """
    Extract the auto-selected variant from the output file.

    Returns 'Homogeneous' or 'Heterogeneous' or None.
    """
    try:
        with open(file_path, 'r') as f:
            content = f.read()
    except FileNotFoundError:
        return None

    # Look for: "Auto variant would select: Homogeneous" or "... Heterogeneous"
    pattern = r'Auto variant would select:\s*(Homogeneous|Heterogeneous)'
    match = re.search(pattern, content)

    return match.group(1) if match else None


def find_output_files(base_name: str, compiler: str,
                      output_dir: str) -> Tuple[Path, Path]:
    """
    Find output files for a dataset, searching for compiler-specific names.

    Returns (homo_file, hetero_file) paths.
    Files may not exist - caller should check.
    """
    cpu_model = get_cpu_model().replace(' ', '_').replace('/',
                                                          '-').replace('@', '')

    # Try with CPU model and compiler prefix
    homo_file = Path(
        output_dir) / f"{cpu_model}_{compiler}_{base_name}-homo.raw"
    hetero_file = Path(
        output_dir) / f"{cpu_model}_{compiler}_{base_name}-hetero.raw"

    # Fallback: try without CPU model prefix (backward compatibility)
    if not homo_file.exists():
        homo_file = Path(output_dir) / f"{base_name}-homo.raw"
        hetero_file = Path(output_dir) / f"{base_name}-hetero.raw"

    return homo_file, hetero_file


def get_dataset_results(base_name: str, compiler: str,
                        output_dir: str) -> Optional[Tuple[float, float, str]]:
    """
    Get results for a dataset (homogeneous, heterogeneous, auto-selected).

    Returns (homo_time, hetero_time, selected_variant) or None if data missing.
    """
    homo_file, hetero_file = find_output_files(
        base_name, compiler, output_dir)

    # Parse timing data
    homo_data = parse_benchmark_output(homo_file)
    hetero_data = parse_benchmark_output(hetero_file)

    if not homo_data or not hetero_data:
        return None

    homo_time = homo_data.get('champagne_lemire')
    hetero_time = hetero_data.get('champagne_lemire')

    if homo_time is None or hetero_time is None:
        return None

    # Determine auto-selected variant from homo file (both report it)
    selected = extract_auto_selection(homo_file)
    if selected is None:
        # Fallback: try hetero file
        selected = extract_auto_selection(hetero_file)
    if selected is None:
        # Last fallback: pick the faster one
        selected = 'Homogeneous' if homo_time <= hetero_time else 'Heterogeneous'

    return (homo_time, hetero_time, selected)


def format_time_cell(time: float, is_winner: bool) -> str:
    """Format a time value for LaTeX table, bolding if winner."""
    formatted = f"{time:.2f}"
    if is_winner:
        return f"\\textbf{{{formatted}}}"
    return formatted


def generate_latex_table(compiler: str, output_dir: str) -> str:
    """Generate the complete LaTeX table."""
    lines = []

    # Table header
    lines.append(r"\begin{table}")
    lines.append(
        r"  \caption{Performance comparison of homogeneous vs heterogeneous variants"
    )
    lines.append(
        r"  across different datasets. Times shown in nanoseconds per integer (ns/i)."
    )
    lines.append(
        r"  The \textbf{bold} value indicates the faster variant for each dataset."
    )
    lines.append(
        r"  The ``Selected'' column shows which variant was chosen by auto-detection.}%"
    )
    lines.append(r"  \label{tab:homogeneous_vs_heterogeneous}")
    lines.append(r"  \centering")
    lines.append(r"  \begin{tabular}{lrrr}")
    lines.append(r"    \toprule")
    lines.append(
        r"    Dataset & Homogeneous (ns/i) & Heterogeneous (ns/i) & Selected \\"
    )
    lines.append(r"    \midrule")

    # Data rows
    missing_datasets = []
    for base_name, display_name in DATASETS:
        result = get_dataset_results(base_name, compiler, output_dir)

        if result is None:
            missing_datasets.append(display_name)
            lines.append(f"    {display_name} & --- & --- & --- \\\\")
            continue

        homo_time, hetero_time, selected = result

        # Determine winner (faster = lower time)
        homo_is_winner = homo_time <= hetero_time
        hetero_is_winner = not homo_is_winner

        # Format cells
        homo_cell = format_time_cell(homo_time, homo_is_winner)
        hetero_cell = format_time_cell(hetero_time, hetero_is_winner)
        selected_abbrev = "Homo" if selected == "Homogeneous" else "Hetero"

        lines.append(
            f"    {display_name} & {homo_cell} & {hetero_cell} & {selected_abbrev} \\\\"
        )

    # Table footer
    lines.append(r"    \bottomrule")
    lines.append(r"  \end{tabular}\restartrowcolors")
    lines.append(r"\end{table}")

    # Warnings for missing data
    if missing_datasets:
        print("\nWARNING: Missing data for the following datasets:")
        for name in missing_datasets:
            print(f"  - {name}")
        print()

    return "\n".join(lines)


def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description="Generate LaTeX table from benchmark outputs")
    parser.add_argument(
        "--compiler",
        default="g++",
        help="Compiler to use for finding output files (default: g++)")
    parser.add_argument(
        "--input-dir",
        default="./outputs",
        help="Directory containing raw benchmark files (default: ./outputs)")
    parser.add_argument(
        "--output-file",
        default="table_homogeneous_vs_heterogeneous.tex",
        help="Output LaTeX file name (default: table_homogeneous_vs_heterogeneous.tex)"
    )
    return parser.parse_args()


def main():
    """Main entry point."""
    args = parse_args()

    # Check if input directory exists
    if not Path(args.input_dir).is_dir():
        print(f"ERROR: Input directory not found: {args.input_dir}/")
        print(
            "Please run generate_raw_outputs.py first to generate benchmark data."
        )
        sys.exit(1)

    print("Parsing benchmark outputs...")
    print(f"Reading from: {args.input_dir}/")
    print(f"Compiler: {args.compiler}\n")

    # Generate table
    latex_table = generate_latex_table(args.compiler, args.input_dir)

    # Save to file in input directory
    output_path = Path(args.input_dir) / args.output_file
    with open(output_path, 'w') as f:
        f.write(latex_table)

    print(f"\nLaTeX table generated: {output_path}")
    print("\nTable preview:")
    print("=" * 80)
    print(latex_table)
    print("=" * 80)

    print("\nYou can include this table in your LaTeX document with:")
    print(f"  \\input{{{output_path}}}")


if __name__ == "__main__":
    main()
